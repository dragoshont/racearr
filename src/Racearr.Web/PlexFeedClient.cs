using Racearr.Core;

namespace Racearr.Web;

/// <summary>
/// Fetches a Plex watchlist feed over HTTPS and hands the raw JSON to
/// <see cref="PlexWatchlistFeed.Parse"/>. This is the only outbound call racearr makes to the
/// public internet, and it is the exact seam that killed the previous integration.
/// </summary>
/// <remarks>
/// <para><b>Why no Plex token is sent.</b> A watchlist feed id is itself a read credential:
/// <c>GET https://rss.plex.tv/&lt;id&gt;</c> returns the household's whole watchlist with no
/// token, no cookie and no session (verified 2026-11-22). So sending the account token buys
/// nothing here and costs a lot — the old integration held a six-service-wide account token and
/// printed it in plaintext in its own warning lines on every poll. A feed id is narrower
/// (read-only, revocable, regenerated by one click in the Plex UI), so this process holds the
/// weakest thing that still works. Consequence for logging: the feed id must be treated like a
/// secret and never appear in a log line or a metric label; callers use <c>feed1</c>, <c>feed2</c>.</para>
///
/// <para><b>The redirect, which is the whole reason this class exists.</b> <c>rss.plex.tv</c>
/// answers 302 to a presigned S3 URL carrying <c>X-Amz-SignedHeaders=host</c>, so the signature
/// covers the <c>Host</c> header of the request that fetches it. <see cref="HttpClient"/>
/// rebuilds <c>Host</c> per connection, which is correct, and the default
/// <see cref="HttpClientHandler.AllowAutoRedirect"/> follows the chain for us. Measured on the
/// live feed: correct Host → 200; the original header replayed → <c>403 SignatureDoesNotMatch</c>.
/// The previous client replayed it and failed every single poll for a day while reporting
/// <c>Running</c> and <c>Ready</c>. Therefore, and this is not style:</para>
/// <list type="bullet">
///   <item>never set an explicit <c>Host</c> header on this client;</item>
///   <item>never disable automatic redirects and hand-follow them (that is where the replay happens);</item>
///   <item>never log <c>RequestMessage.RequestUri</c> — it contains the feed id.</item>
/// </list>
/// </remarks>
public sealed class PlexFeedClient(HttpClient http, ILogger<PlexFeedClient> log) : IPlexFeedSource
{
    /// <summary>
    /// Fetch one feed. Never throws for an HTTP-level failure: a 403, a 500 and a truncated body
    /// are all results the caller must be able to distinguish from "watchlist is empty", because
    /// "empty" clears the stall alert and "unreadable" must not.
    /// </summary>
    public async Task<PlexFeedResult> FetchAsync(string feedId, CancellationToken ct)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(feedId);

        var url = $"https://rss.plex.tv/{Uri.EscapeDataString(feedId.Trim())}?format=json";
        try
        {
            using var req = new HttpRequestMessage(HttpMethod.Get, url);
            using var resp = await http.SendAsync(req, ct);
            var status = (int)resp.StatusCode;

            // Body is read even on failure: an HTML challenge page and a JSON error have
            // different remediation (Cloudflare block vs Plex revoking the feed), and the length
            // alone distinguishes them in a log line without quoting the content.
            var body = await resp.Content.ReadAsStringAsync(ct);

            if (resp.IsSuccessStatusCode)
                return PlexFeedResult.Delivered(status, body);

            // Host only, never the path: the path is the credential.
            log.LogWarning("watchlist feed unreadable: HTTP {Status} from {Host} ({Length} bytes)",
                status, resp.RequestMessage?.RequestUri?.Host ?? "rss.plex.tv", body.Length);
            return PlexFeedResult.Rejected(status, body);
        }
        catch (OperationCanceledException) when (ct.IsCancellationRequested)
        {
            throw;      // shutdown, not a feed problem — must not be counted as a probe failure
        }
        catch (HttpRequestException ex)
        {
            log.LogWarning("watchlist feed request failed: {Reason}", ex.GetType().Name);
            return PlexFeedResult.TransportFailure(0, ex.GetType().Name);
        }
        catch (TaskCanceledException)
        {
            // HttpClient timeout surfaces this way. Distinct label from HttpRequestException so
            // "Plex is answering slowly" is separable from "DNS/route is gone".
            log.LogWarning("watchlist feed request timed out");
            return PlexFeedResult.TransportFailure(0, "timeout");
        }
    }
}
